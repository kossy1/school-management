// Generate past 20 school days of attendance
const generatePastAttendance = (): AttendanceRecord[] => {
  const records: AttendanceRecord[] = [];
  const today = new Date();
  
  let count = 0;
  let dayOffset = 0;

  while (count < 20) {
    const d = new Date(today);
    d.setDate(today.getDate() - dayOffset);
    dayOffset++;
    
    // Skip weekends
    if (d.getDay() === 0 || d.getDay() === 6) continue;
    
    const dateStr = d.toISOString().split('T')[0];
    
    // Chukwuemeka Adeleke (std-1): 96% attendance, 1 late, 1 excused
    let chukwuStatus: 'present' | 'absent' | 'late' | 'excused' = 'present';
    let chukwuRemarks = 'Present at morning assembly';
    if (count === 4) {
      chukwuStatus = 'excused';
      chukwuRemarks = 'Inter-state STEM Olympiad selection trial in Abuja';
    } else if (count === 11) {
      chukwuStatus = 'late';
      chukwuRemarks = 'Lekki Toll Gate traffic delay; arrived 8:15 AM';
    }

    records.push({
      id: `att-chukwu-${count}`,
      studentId: 'std-1',
      date: dateStr,
      status: chukwuStatus,
      remarks: chukwuRemarks,
      notifiedParent: chukwuStatus !== 'present',
    });

    // Zainab Adeleke (std-2): 98% attendance
    records.push({
      id: `att-zainab-${count}`,
      studentId: 'std-2',
      date: dateStr,
      status: count === 7 ? 'late' : 'present',
      remarks: count === 7 ? 'Late for prefect roll call' : 'Present and seated',
      notifiedParent: count === 7,
    });

    // Classmates
    records.push(
      { id: `att-3-${count}`, studentId: 'std-3', date: dateStr, status: 'present', remarks: 'Present' },
      { id: `att-4-${count}`, studentId: 'std-4', date: dateStr, status: count === 2 ? 'absent' : 'present', remarks: count === 2 ? 'Reported malaria fever' : 'Present', notifiedParent: count === 2 },
      { id: `att-5-${count}`, studentId: 'std-5', date: dateStr, status: 'present', remarks: 'Present' },
      { id: `att-6-${count}`, studentId: 'std-6', date: dateStr, status: count === 9 ? 'late' : 'present', remarks: count === 9 ? 'Third Mainland Bridge traffic' : 'Present' }
    );

    count++;
  }

  return records;
};

